import type { LessonGuide, NoteReadingExercise } from './lessonGuides';

interface EduXGuideDefinition {
  id: string;
  objective: string;
  principle: string;
  steps: string[];
  drills: { name: string; how: string; reps: string }[];
  checks: string[];
  selfCheck: string[];
  quizQuestion: string;
  quizOptions: string[];
  correctIndex: number;
  quizExplanation: string;
  noteReadingExercises?: NoteReadingExercise[];
}

const progression = [
  { level: 'Beginner' as const, marker: 'You can perform the exercise slowly without throat pain or breath panic.' },
  { level: 'Intermediate' as const, marker: 'You keep the target coordination while the pattern moves through several notes.' },
  { level: 'Advanced' as const, marker: 'You can repeat the task under recording pressure and still meet the acoustic target.' },
  { level: 'Professional' as const, marker: 'The coordination becomes automatic and survives song tempo, text, and performance stress.' },
];

function quiz(def: EduXGuideDefinition) {
  return [
    {
      question: def.quizQuestion,
      options: def.quizOptions,
      correctIndex: def.correctIndex,
      explanation: def.quizExplanation,
    },
    {
      question: 'What must happen before you start the AI practice step?',
      options: ['Guess the answer and skip ahead', 'Finish the quiz correctly first', 'Force louder singing until the mic reacts'],
      correctIndex: 1,
      explanation: 'EduX uses a flipped classroom flow: understand the concept, pass the quiz, then practise with pitch or acoustic feedback.',
    },
  ];
}

function makeGuide(def: EduXGuideDefinition): LessonGuide {
  return {
    objective: def.objective,
    why: def.principle,
    steps: def.steps,
    drills: def.drills,
    feelFor: [
      'A steady tone that feels repeatable rather than forced.',
      'Easy breath release with the jaw, tongue, and neck staying loose.',
      'Pitch feedback moving toward the target instead of drifting wider over time.',
    ],
    mistakes: [
      'Pushing volume to hit a target instead of improving coordination.',
      'Ignoring throat pain, hoarseness, or scratchiness after a repetition.',
      'Moving to the practice panel before the quiz concept is clear.',
    ],
    simeChecks: def.checks,
    selfCheck: def.selfCheck,
    progression,
    proTips: [
      'Record one clean attempt before increasing range, speed, or volume.',
      'If the metric fails twice, make the exercise smaller: softer, slower, and closer to speech pitch.',
      'End the session while the voice still feels fresh; vocal learning compounds better than forcing one long take.',
    ],
    quiz: quiz(def),
    noteReadingExercises: def.noteReadingExercises,
  };
}

function noteTargets(notes: string[]) {
  return notes.map((note, index) => ({
    note,
    label: `Sheet note ${index + 1}`,
    hint: `Sing exactly ${note}; the pass window is +/-50 cents from the written pitch.`,
  }));
}

function noteExercise(title: string, notes: string[]): NoteReadingExercise {
  return {
    title,
    instructions: 'Read each note on the staff, sing the written pitch, and hold it until the meter confirms the target. Do not pass by singing a nearby note.',
    clef: 'treble',
    passScore: 100,
    toleranceCents: 50,
    holdMs: 550,
    targets: noteTargets(notes),
  };
}

